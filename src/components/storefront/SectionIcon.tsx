export function SectionIcon({ name, className = "w-6 h-6" }: { name?: string | null; className?: string }) {
  const raw = String(name || "").trim();
  if (raw && /[^\x00-\x7F]/.test(raw)) return <span className="leading-none">{raw}</span>;
  const Icon = ICONS[raw.toLowerCase().replace(/[^a-z]/g, "")] || Sparkles;
  return <Icon className={className} aria-hidden="true" />;
}

