export function storeText(lang: StoreLang) {
  const dict: Record<string, string> = lang === "ar" ? AR : FR;
  return (key: StoreTextKey, vars?: Record<string, string | number>) => {
    let text = dict[key] ?? FR[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    return text;
  };
}

export function governorateLabel(name: string, lang: StoreLang) {
  return lang === "ar" ? GOVERNORATES_AR[name] || name : name;
}

export function formatStoreMoney(value: number | string, lang: StoreLang) {
  const amount = Number(value) || 0;
  const number = amount.toFixed(3).replace(".", ",");
  return lang === "ar" ? `${number} د.ت` : `${number} DT`;
}

export function normalizeStorefrontLanguage(value: unknown): StorefrontLanguageSetting {
  return value === "ar" || value === "both" ? value : "fr";
}

export function initialStoreLang(setting: StorefrontLanguageSetting, slug: string): StoreLang {
  if (setting !== "both") return setting;
  if (typeof window === "undefined") return "fr";
  try {
    const saved = window.localStorage.getItem(`store_lang:${slug}`);
    if (saved === "fr" || saved === "ar") return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("ar") ? "ar" : "fr";
}

export function orderErrorText(code: unknown, t: ReturnType<typeof storeText>) {
  const known: Record<string, StoreTextKey> = {
    invalid_phone: "errors.invalid_phone",
    invalid_email: "errors.invalid_email",
    missing_fields: "errors.missing_fields",
    product_unavailable: "errors.product_unavailable",
    out_of_stock: "errors.out_of_stock",
    variant_required: "errors.variant_required",
    store_unavailable: "errors.store_unavailable",
  };
  return t(known[String(code)] || "errors.generic");
}
